import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const PRIZE_POOL = [
  { id: 1, name: '무료 1게임' },
  { id: 2, name: '2000 point' },
  { id: 3, name: '음료 선택권' },
  { id: 4, name: '스낵 선택권' },
];
const DECLINED = new Set([2, 9, 20]);

function pad4(n) {
  return String(n).padStart(4, '0');
}
function formatPhone(seed) {
  const a = 1000 + (seed % 9000);
  const b = 1000 + ((seed * 7 + 13) % 9000);
  return `010-${pad4(a)}-${pad4(b)}`;
}
function randomDateBetween(start, end, seed) {
  const ratio = ((seed * 9301 + 49297) % 10000) / 10000;
  return new Date(start.getTime() + Math.floor(ratio * (end.getTime() - start.getTime())));
}
function generateCoupon(seed) {
  const part1 = pad4(1000 + ((seed * 17) % 9000));
  const part2 = pad4(1000 + ((seed * 31) % 9000));
  return `C-${part1}-${part2}`;
}
function sqlStr(v) {
  return `'${String(v).replace(/'/g, "''")}'`;
}

const year = 2026;
const rangeStart = new Date(`${year}-04-01T10:00:00+09:00`);
const rangeEnd = new Date(`${year}-05-31T21:00:00+09:00`);
const phoneBySeed = new Map();
const logs = [];

for (let i = 0; i < 52; i++) {
  const phoneSeed = 100 + (i % 28);
  if (!phoneBySeed.has(phoneSeed)) phoneBySeed.set(phoneSeed, formatPhone(phoneSeed));
  const phone = phoneBySeed.get(phoneSeed);
  const prize = PRIZE_POOL[i % 4];
  const createdAt = randomDateBetween(rangeStart, rangeEnd, i + 1);
  const isUsed = i % 3 === 0;
  const usedAt = isUsed
    ? new Date(createdAt.getTime() + 1000 * 60 * (30 + (i % 120))).toISOString()
    : null;
  logs.push({
    phone,
    prize,
    createdAt: createdAt.toISOString(),
    isUsed,
    usedAt,
    coupon: generateCoupon(5000 + i),
  });
}

logs.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));

const logRows = logs
  .map(
    (l) =>
      `  (${sqlStr(l.phone)}, ${sqlStr(l.prize.name)}, ${l.prize.id}, ${sqlStr(l.coupon)}, ${l.isUsed}, ${
        l.usedAt ? sqlStr(l.usedAt) : 'NULL'
      }, true, ${sqlStr(l.createdAt)})`
  )
  .join(',\n');

const consentRows = [];
for (const [seed, phone] of phoneBySeed.entries()) {
  const phoneLogs = logs.filter((l) => l.phone === phone);
  const firstAt = phoneLogs[phoneLogs.length - 1]?.createdAt ?? rangeStart.toISOString();
  const index = seed - 100;
  const isDeclined = DECLINED.has(index);
  const declinedAt = isDeclined
    ? new Date(new Date(firstAt).getTime() + 1000 * 60 * 60 * 24 * 3).toISOString()
    : null;
  consentRows.push(
    `  (${sqlStr(phone)}, ${sqlStr(isDeclined ? 'declined' : 'agreed')}, ${
      isDeclined ? 'NULL' : sqlStr(firstAt)
    }, ${declinedAt ? sqlStr(declinedAt) : 'NULL'}, ${sqlStr(declinedAt ?? firstAt)})`
  );
}

const outPath = path.join(__dirname, '..', 'supabase', 'seed-data.generated.sql');
fs.writeFileSync(
  outPath,
  `-- Auto-generated by scripts/generate-seed-sql.mjs\n\n${logRows}\n\n-- consents\n${consentRows.join(',\n')}\n`,
  'utf8'
);
console.log('Wrote', outPath);
